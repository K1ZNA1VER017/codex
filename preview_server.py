class ChronicaHandler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=DIRECTORY, **kwargs)

    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        if parsed.path == "/" or parsed.path == "/index.php":
            self.path = "/index.html"
            return super().do_GET()

        if parsed.path == "/api.php":
            self.handle_api_get(parsed)
            return

        return super().do_GET()

    def do_POST(self):
        parsed = urllib.parse.urlparse(self.path)
        if parsed.path == "/api.php":
            self.handle_api_post(parsed)
            return

        return super().do_POST()

    def handle_api_get(self, parsed):
        params = urllib.parse.parse_qs(parsed.query)
        action = params.get("action", ["get_data"])[0]

        if action == "get_data" or action == "":
            conn = sqlite3.connect(DB_FILE)
            conn.row_factory = sqlite3.Row
            cur = conn.cursor()

            cur.execute("SELECT * FROM stages ORDER BY sort_order ASC, id ASC")
            stages = [dict(row) for row in cur.fetchall()]

            cur.execute("SELECT * FROM tasks ORDER BY stage_id ASC, id ASC")
            raw_tasks = [dict(row) for row in cur.fetchall()]
            tasks = []
            for t in raw_tasks:
                try:
                    t["checklist_items"] = json.loads(t["checklist"]) if t["checklist"] else []
                except Exception:
                    t["checklist_items"] = []
                tasks.append(t)

            cur.execute("SELECT * FROM profile LIMIT 1")
            prof_row = cur.fetchone()
            profile = dict(prof_row) if prof_row else {}

            conn.close()

            total = len(tasks)
            completed = sum(1 for t in tasks if t["status"] == "completed")
            in_prog = sum(1 for t in tasks if t["status"] == "in_progress")
            todo = sum(1 for t in tasks if t["status"] == "todo")
            total_hours = sum(t["estimated_hours"] or 0 for t in tasks)
            comp_hours = sum(t["estimated_hours"] or 0 for t in tasks if t["status"] == "completed")
            pct = round((completed / total * 100)) if total > 0 else 0

            if pct < 25:
                rank = {"title": "Оруженосец Франчайзи", "subtitle": "Базовые регламенты, кассовая рутина и пробуждение к кодингу", "badge": "I"}
            elif pct < 50:
                rank = {"title": "Адепт Элемента и API", "subtitle": "Полномочия веб-интеграций и владение 1С:Предприятие.Элемент", "badge": "II"}
            elif pct < 75:
                rank = {"title": "Рыцарь Платформы и БСП", "subtitle": "Официальный сертификат Профессионала и стандарты Enterprise", "badge": "III"}
            elif pct < 95:
                rank = {"title": "Магистр Корпоративных Архитектур", "subtitle": "Крепкое боевое портфолио, диплом закрыт, открыты двери лучших офферов", "badge": "IV"}
            else:
                rank = {"title": "Грандмастер 1С / Middle-Инженер", "subtitle": "Триумфальный вход в штат с высоким окладом и новыми масштабами", "badge": "V"}

            payload = {
                "status": "success",
                "stages": stages,
                "tasks": tasks,
                "profile": profile,
                "stats": {
                    "total_tasks": total,
                    "completed_tasks": completed,
                    "in_progress_tasks": in_prog,
                    "todo_tasks": todo,
                    "percentage": pct,
                    "total_hours": total_hours,
                    "completed_hours": comp_hours,
                    "rank": rank
                }
            }

            self.send_json(payload)
        else:
            self.send_json({"status": "error", "message": "Неизвестное действие"}, status=400)

    def handle_api_post(self, parsed):
        content_length = int(self.headers.get("Content-Length", 0))
        body = self.rfile.read(content_length).decode("utf-8")
        try:
            data = json.loads(body) if body else {}
        except Exception:
            data = {}

        params = urllib.parse.parse_qs(parsed.query)
        action = params.get("action", [data.get("action", "")])[0]

        conn = sqlite3.connect(DB_FILE)
        cur = conn.cursor()

        if action == "update_status":
            task_id = int(data.get("task_id", 0))
            new_status = data.get("status", "")
            if task_id and new_status in ["todo", "in_progress", "completed"]:
                cur.execute("UPDATE tasks SET status = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?", (new_status, task_id))
                conn.commit()
                conn.close()
                self.send_json({"status": "success", "message": "Статус обновлен", "task_id": task_id, "new_status": new_status})
                return

        elif action == "update_notes":
            task_id = int(data.get("task_id", 0))
            notes = data.get("notes", "")
            if task_id:
                cur.execute("UPDATE tasks SET notes = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?", (notes, task_id))
                conn.commit()
                conn.close()
                self.send_json({"status": "success", "message": "Заметка сохранена", "task_id": task_id})
                return

        elif action == "reset_defaults":
            cur.execute("DELETE FROM tasks")
            cur.execute("DELETE FROM stages")
            cur.execute("DELETE FROM profile")
            seed_sqlite(conn)
            conn.close()
            self.send_json({"status": "success", "message": "Данные сброшены"})
            return

        conn.close()
        self.send_json({"status": "error", "message": "Некорректный запрос"}, status=400)

    def send_json(self, data, status=200):
        body = json.dumps(data, ensure_ascii=False, indent=2).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

