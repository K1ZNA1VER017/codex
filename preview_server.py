def init_sqlite_db():
    conn = sqlite3.connect(DB_FILE)
    cur = conn.cursor()
    cur.execute("""
    CREATE TABLE IF NOT EXISTS stages (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        stage_num INTEGER,
        code TEXT UNIQUE,
        roman TEXT,
        title TEXT,
        period TEXT,
        quest_title TEXT,
        description TEXT,
        icon TEXT,
        sort_order INTEGER
    )""")
    cur.execute("""
    CREATE TABLE IF NOT EXISTS tasks (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        stage_id INTEGER,
        task_code TEXT UNIQUE,
        title TEXT,
        category TEXT,
        priority TEXT,
        status TEXT,
        estimated_hours INTEGER,
        description TEXT,
        skills_after TEXT,
        deliverables TEXT,
        checklist TEXT,
        notes TEXT,
        completed_at TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )""")
    cur.execute("""
    CREATE TABLE IF NOT EXISTS profile (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_title TEXT,
        current_role TEXT,
        target_role TEXT,
        experience_years REAL,
        college_months_left INTEGER,
        target_salary_min INTEGER,
        target_salary_max INTEGER,
        motto TEXT
    )""")
    conn.commit()

    # Check if empty, seed from schema
    cur.execute("SELECT COUNT(*) FROM stages")
    if cur.fetchone()[0] == 0:
        seed_sqlite(conn)
    conn.close()

